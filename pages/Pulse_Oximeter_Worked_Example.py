def _paired_measurement_svg(abg_value: int, abg_label: str) -> str:
    """
    Static diagram (not animated - see feedback on flickering icons):
    a drawn pulse-oximeter clip and a drawn blood-sample vial, taken
    minutes apart on the same patient. The device reading is fixed at
    94%; abg_value/abg_label vary with the toggle above this diagram, so
    a reader can compare the two acquisition methods on the same patient
    under both a typical and an occult-hypoxemia outcome.

    Both icons are deliberately abstract shapes (a clip, a vial), not a
    depiction of a hand or skin, since this page's subject is a
    skin-pigmentation-linked measurement error and a literal illustrated
    hand would invite exactly the kind of visual judgment this page is
    about, not illustrate the mechanism. Hover either icon (native SVG
    <title>) for detail.
    """

