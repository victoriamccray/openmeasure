def _light_absorption_animation_svg() -> str:
    """
    A slow, continuous loop demonstrating why pulse oximetry works at
    all: an artery's blood volume rises and falls with each heartbeat,
    so the light reaching the detector dims and brightens in step. This
    pulsatile signal (the "pulse" in pulse oximeter) is what the device
    actually measures; SpO2 comes from comparing how much red versus
    infrared light varies with that pulse.

    Deliberately not the flickering-icon kind of animation this project
    otherwise avoids: motion is smooth and continuous (opacity/radius
    eased in and out over ~1.1s, no hard cuts or strobing), and
    prefers-reduced-motion disables it entirely in favor of a static
    mid-pulse frame, since the surrounding prose already states the
    mechanism in words - the animation illustrates it, nothing here
    depends on seeing it move.
    """

    return f"""
    <style>
      @media (prefers-reduced-motion: no-preference) {{
        .pulseox-artery {{ animation: pulseox-artery-pulse 1.1s ease-in-out infinite; }}
        .pulseox-beam {{ animation: pulseox-beam-dim 1.1s ease-in-out infinite; }}
      }}
      @keyframes pulseox-artery-pulse {{
        0%, 100% {{ r: 5; opacity: 0.55; }}
        50% {{ r: 8; opacity: 0.9; }}
      }}
      @keyframes pulseox-beam-dim {{
        0%, 100% {{ opacity: 0.95; }}
        50% {{ opacity: 0.55; }}
      }}
    </style>
    <svg width="100%" height="120" viewBox="0 0 420 120" preserveAspectRatio="xMidYMid meet">
      <g style="cursor:help;">
        <title>Two LEDs (red and infrared light) shine through tissue to a detector.</title>
        <rect x="15" y="35" width="34" height="50" rx="6" fill="none" stroke="{INK_MUTED}" stroke-width="1.5"/>
        <circle cx="32" cy="52" r="4" fill="{ACCENT_2}"/>
        <circle cx="32" cy="68" r="4" fill="#7a2020"/>
        <text x="32" y="100" font-size="9" fill="{INK_MUTED}" text-anchor="middle">Red + infrared LEDs</text>
      </g>
      <rect class="pulseox-beam" x="49" y="44" width="130" height="6" fill="{ACCENT_2}" fill-opacity="0.5"/>
      <rect class="pulseox-beam" x="49" y="60" width="130" height="6" fill="#7a2020" fill-opacity="0.5"/>
      <g style="cursor:help;">
        <title>Arterial blood volume rises and falls with each heartbeat, changing how much light passes through.</title>
        <rect x="179" y="30" width="62" height="60" rx="8" fill="none" stroke="{INK_MUTED}" stroke-width="1.5"/>
        <circle class="pulseox-artery" cx="210" cy="60" r="6" fill="{ACCENT}"/>
        <text x="210" y="105" font-size="9" fill="{INK_MUTED}" text-anchor="middle">Tissue (pulsing artery)</text>
      </g>
      <rect class="pulseox-beam" x="241" y="44" width="130" height="6" fill="{ACCENT_2}" fill-opacity="0.5"/>
      <rect class="pulseox-beam" x="241" y="60" width="130" height="6" fill="#7a2020" fill-opacity="0.5"/>
      <g style="cursor:help;">
        <title>The detector reads how much of each wavelength arrived, over and over, many times a second.</title>
        <rect x="371" y="35" width="34" height="50" rx="6" fill="none" stroke="{INK_MUTED}" stroke-width="1.5"/>
        <path d="M380 60 h6 l4 -10 l4 20 l4 -14 l4 8 h6" fill="none" stroke="{ACCENT}" stroke-width="1.5"/>
        <text x="388" y="100" font-size="9" fill="{INK_MUTED}" text-anchor="middle">Detector</text>
      </g>
    </svg>
    """


def _rate_chart_spec(cohort_id: str) -> dict:
    """
    A horizontal bar per group, x-axis explicitly labeled and expressed
    as a percentage, so the axis is self-explanatory without relying on
    a reader hovering or reading a caption elsewhere. One color for both
    bars: the axis position, not a color code, is what carries the
    group comparison here.
    """

    cohort = pod.PUBLISHED_COHORTS[cohort_id]
    rows = [
        {"Group": gr.group, "rate": gr.occult_hypoxemia_rate}
        for gr in cohort.group_rates
    ]

    return {
        "data": {"values": rows},
        "mark": {"type": "bar", "color": ACCENT},
        "encoding": {
            "y": {"field": "Group", "type": "nominal", "title": None},
            "x": {
                "field": "rate",
                "type": "quantitative",
                "title": "Occult hypoxemia rate (%)",
                "axis": {"format": ".0%"},
            },
        },
        "width": "container",
        "height": 120,
    }


